"""Generate project/ng2/src/ng2_trace_all.cpp: a diagnostic TU that overrides every
recompiled guest function (they are weak aliases of __imp__sub_X) with a gated entry
counter. Build with -DNG2_TRACE_ALL=ON. Triggers (files next to ng2.exe):
  ng2_trace_on   -> zero counters, start counting
  ng2_trace_off_<tag> -> stop, write ng2_trace_<tag>.txt (addr count last_lr)
Usage: python -I tools/gen_trace_all.py
"""
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
init = os.path.join(root, "project", "ng2", "generated", "default", "ng2_init.cpp")
names = []
for line in open(init, encoding="utf-8"):
    m = re.match(r"\s*\{ 0x([0-9A-F]{8}), sub_([0-9A-F]{8}) \},", line)
    if m and m.group(1) == m.group(2):
        names.append(m.group(1))
# Skip guest functions the app already overrides (strong `REX_FUNC(sub_X) {` definitions).
src_dir = os.path.join(root, "project", "ng2", "src")
overridden = set()
for fn in os.listdir(src_dir):
    if fn.endswith(".cpp") and fn != "ng2_trace_all.cpp":
        text = open(os.path.join(src_dir, fn), encoding="utf-8").read()
        overridden |= set(re.findall(r"REX_FUNC\(sub_([0-9A-F]{8})\)\s*\{", text))
names = [n for n in names if n not in overridden]
print("skipping app overrides:", sorted(overridden))
out = os.path.join(src_dir, "ng2_trace_all.cpp")
with open(out, "w", encoding="utf-8") as f:
    NL = chr(10)
    BS = chr(92)
    f.write("// GENERATED by tools/gen_trace_all.py (NG2 DIAG). Do not edit." + NL)
    f.write("#include <rex/ppc.h>" + NL + "#include <rex/ppc/func.h>" + NL)
    f.write('#include "ng2_trace_all.h"' + NL + NL)
    f.write("namespace ng2trace {" + NL + "constexpr uint32_t kCount = %d;" % len(names) + NL)
    f.write("const uint32_t kAddrs[kCount] = {" + NL)
    for i in range(0, len(names), 8):
        f.write("  " + ", ".join("0x" + n for n in names[i:i + 8]) + "," + NL)
    f.write("};" + NL + "uint32_t g_counts[kCount];" + NL + "uint32_t g_lr[kCount];" + NL)
    f.write("uint32_t Count() { return kCount; }" + NL + "}  // namespace ng2trace" + NL + NL)
    macro = [
        "#define T(i, a)",
        '  extern "C" REX_FUNC(__imp__sub_##a);',
        '  extern "C" REX_FUNC(sub_##a) {',
        "    if (ng2trace::g_on.load(std::memory_order_relaxed)) {",
        "      ++ng2trace::g_counts[i]; ng2trace::g_lr[i] = uint32_t(ctx.lr); }",
        "    __imp__sub_##a(ctx, base); }",
    ]
    f.write((" " + BS + NL).join(macro) + NL + NL)
    for i, n in enumerate(names):
        f.write("T(%d, %s)" % (i, n) + NL)
print(len(names), "functions ->", out)
