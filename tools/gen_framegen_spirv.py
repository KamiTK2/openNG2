"""Generate the Vulkan frame generation SPIR-V from the D3D12 interpolator's HLSL.

The HLSL lives once, in tools/rexglue-sdk/src/ui/d3d12/d3d12_frame_interpolator.cpp
(kShaderSource). This script swaps its D3D12 resource declarations for Vulkan ones
(push constants, explicit bindings, a per-pass storage image format), compiles each entry
point with DXC from the Vulkan SDK and writes
tools/rexglue-sdk/src/ui/vulkan/ng2_frame_interpolator_spirv.h.

Usage: python -I tools/gen_framegen_spirv.py [path to dxc.exe]
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SDK = os.path.join(ROOT, 'tools', 'rexglue-sdk')
SRC = os.path.join(SDK, 'src', 'ui', 'd3d12', 'd3d12_frame_interpolator.cpp')
OUT = os.path.join(SDK, 'src', 'ui', 'vulkan', 'ng2_frame_interpolator_spirv.h')
DXC = sys.argv[1] if len(sys.argv) > 1 else r'C:\VulkanSDK\1.4.363.0\Bin\dxc.exe'
SPIRV_VAL = os.path.join(os.path.dirname(DXC), 'spirv-val.exe')

# Entry point -> storage image format of u0 (must match the Vulkan images).
PASSES = [
    ('CSLuma', 'r16f'),
    ('CSDown', 'r16f'),
    ('CSRefine', 'rgba32f'),
    ('CSSmooth', 'rgba32f'),
    ('CSSynth', 'rgb10a2'),
    ('CSResample', 'rgb10a2'),
]

PRELUDE = r'''
struct RootConstants { uint4 c0; uint4 c1; uint4 c2; uint4 c3; };
[[vk::push_constant]] RootConstants root;
#define c0 root.c0
#define c1 root.c1
#define c2 root.c2
#define c3 root.c3
[[vk::binding(0)]] Texture2D<float4> t0;
[[vk::binding(1)]] Texture2D<float4> t1;
[[vk::binding(2)]] Texture2D<float4> t2;
[[vk::binding(3)]] Texture2D<float4> t3;
[[vk::binding(4)]] [[vk::image_format(U0_FORMAT)]] RWTexture2D<float4> u0;
[[vk::binding(5)]] SamplerState sLinear;
[[vk::binding(6)]] SamplerState sPoint;
'''


def main():
    text = open(SRC, encoding='utf-8').read()
    m = re.search(r'kShaderSource\[\] = R"HLSL\((.*?)\)HLSL";', text, re.S)
    if not m:
        sys.exit('kShaderSource not found')
    hlsl = m.group(1)
    # Drop the D3D12 declarations (cbuffer .. the last sampler).
    start = hlsl.index('cbuffer Root')
    end = hlsl.index('SamplerState sPoint')
    end = hlsl.index('\n', end) + 1
    hlsl = PRELUDE + hlsl[:start] + hlsl[end:]
    out = ['// Generated by tools/gen_framegen_spirv.py from the HLSL in',
           '// ui/d3d12/d3d12_frame_interpolator.cpp - do not edit. NG2 ADDITION.',
           '#pragma once', '#include <cstdint>', '',
           'namespace rex::ui::vulkan::ng2_frame_interpolator_spirv {', '']
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, 'fi.hlsl')
        open(src, 'w', encoding='utf-8').write(hlsl)
        for entry, fmt in PASSES:
            spv = os.path.join(tmp, entry + '.spv')
            cmd = [DXC, '-spirv', '-T', 'cs_6_0', '-E', entry, '-O3',
                   '-fspv-target-env=vulkan1.1', '-D', 'U0_FORMAT="%s"' % fmt, '-Fo', spv, src]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit('dxc failed for %s:\n%s%s' % (entry, r.stdout, r.stderr))
            if os.path.exists(SPIRV_VAL):
                v = subprocess.run([SPIRV_VAL, '--target-env', 'vulkan1.1', spv],
                                   capture_output=True, text=True)
                if v.returncode != 0:
                    sys.exit('spirv-val failed for %s:\n%s%s' % (entry, v.stdout, v.stderr))
            data = open(spv, 'rb').read()
            words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
            out.append('inline constexpr uint32_t k%s[] = {' % entry)
            for i in range(0, len(words), 8):
                out.append('    ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ',')
            out.append('};')
            out.append('')
            print('%s: %d words (%s)' % (entry, len(words), fmt))
    out.append('}  // namespace rex::ui::vulkan::ng2_frame_interpolator_spirv')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
